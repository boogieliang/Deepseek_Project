INDENT = {"t1": 144, "t2": 48, "body": 32, "h": 32, "sub": 32, "sig": 96, "date": 176, "blank": 0}


def set_run_font(run, size=SIZE, font=FONT):
    run.font.size = size
    run.font.name = font
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.insert(0, rfonts)
    rfonts.set(qn("w:ascii"), font)
    rfonts.set(qn("w:hAnsi"), font)
    rfonts.set(qn("w:eastAsia"), font)
    rfonts.set(qn("w:cs"), font)


def main():
    doc = Document(TEMPLATE)
    body = doc.element.body
    for child in list(body.iterchildren()):
        if child.tag != qn("w:sectPr"):
            body.remove(child)

    for kind, text in BLOCKS:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        ind = INDENT[kind]
        if ind and kind not in ("t1", "t2"):
            pf.first_line_indent = Pt(ind)
        else:
            pf.first_line_indent = Pt(0)
        # copy the template body's paragraph properties baseline (no extra spacing)
        pf.space_before = Pt(0) if kind in ("t1", "t2") else None
        pf.space_after = Pt(0) if kind in ("t1", "t2") else None
        if text:
            run = p.add_run(text)
            set_run_font(run)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER if kind in ("t1", "t2") else None
        if kind in ("h", "sub"):
            pf.keep_with_next = True

    cp = doc.core_properties
    cp.title = "突泉县教育局派驻六户村驻村工作队2026年工作总结"
    cp.subject = "2026年驻村工作总结"
    cp.author = "突泉县教育局派驻六户村驻村工作队"

    doc.save(OUT)
    print("saved:", OUT)
    print("paragraphs:", len(doc.paragraphs))
    total = sum(len(t) for k, t in BLOCKS if t)
    print("chars:", total)


if __name__ == "__main__":
    main()





